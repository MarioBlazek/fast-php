<?php
declare(strict_types=1);

namespace FastPhp\Port;

use FastPhp\Analysis\Codebase;
use FastPhp\Analysis\Func;
use FastPhp\Project;

/**
 * Writes the project's Rust workspace (.fast-php/Cargo.toml), one crate per port
 * (ports/<id>/: port.rs for the agent, generated glue.rs, TASK.md), and the app extension
 * (ext/) that bundles every enabled port into one fastphp_app library.
 */
final class Scaffolder
{
    public function __construct(private readonly Project $project)
    {
    }

    public static function snake(string $s): string
    {
        $s = preg_replace('/([a-z0-9])([A-Z])/', '$1_$2', $s);
        $s = preg_replace('/([A-Z]+)([A-Z][a-z])/', '$1_$2', $s);
        $s = strtolower(preg_replace('/[^A-Za-z0-9]+/', '_', $s));
        $s = trim($s, '_');
        return preg_match('/^[0-9]/', $s) ? "_$s" : $s;
    }

    public static function crate(string $id): string
    {
        return 'port_' . self::snake($id);
    }

    public static function native(string $id): string
    {
        return 'fastphp\\' . $id;
    }

    public function workspace(): void
    {
        $tool = Project::toolRoot();
        $dir = $this->project->path();
        @mkdir("$dir/ports", 0777, true);
        @mkdir("$dir/.cargo", 0777, true);
        copy("$tool/rust/.cargo/config.toml", "$dir/.cargo/config.toml");
        $value = json_encode("$tool/rust/fastphp-value", JSON_UNESCAPED_SLASHES);
        $std = json_encode("$tool/rust/fastphp-std", JSON_UNESCAPED_SLASHES);
        file_put_contents("$dir/Cargo.toml", <<<TOML
            # Generated by fast-php. One crate per port in ports/, bundled by ext/.
            [workspace]
            resolver = "3"
            members = ["ports/*", "ext"]

            [workspace.package]
            edition = "2024"
            publish = false

            [workspace.dependencies]
            ext-php-rs = "0.16.5"
            fastphp-value = { path = $value }
            fastphp-std = { path = $std }

            [profile.release]
            opt-level = 3
            lto = "fat"
            codegen-units = 1
            panic = "unwind"
            strip = "debuginfo"

            TOML);
        if (!is_dir("$dir/ext")) {
            $this->ext([]);
        }
    }

    /** The app extension: registers every enabled port. @param list<string> $ids */
    public function ext(array $ids): void
    {
        $dir = $this->project->path('ext');
        @mkdir("$dir/src", 0777, true);
        $deps = '';
        $calls = '';
        foreach ($ids as $id) {
            $crate = self::crate($id);
            $deps .= "$crate = { path = \"../ports/$id\" }\n";
            $calls .= "    let module = $crate::register(module);\n";
        }
        file_put_contents("$dir/Cargo.toml", <<<TOML
            # Generated by fast-php: `fast-php enable` and `disable` rewrite it.
            [package]
            name = "fastphp_app"
            version = "0.0.0"
            edition.workspace = true
            publish.workspace = true

            [lib]
            crate-type = ["cdylib"]

            [dependencies]
            ext-php-rs.workspace = true
            $deps
            TOML);
        file_put_contents("$dir/src/lib.rs", <<<RUST
            //! Generated by fast-php: every enabled port in one extension.
            //! FAST_PHP_DISABLE=1 in the environment loads it with no functions, so the app runs as plain PHP.
            #![cfg_attr(windows, feature(abi_vectorcall))]

            use ext_php_rs::prelude::*;

            #[php_module]
            pub fn get_module(module: ModuleBuilder) -> ModuleBuilder {
                if std::env::var("FAST_PHP_DISABLE").is_ok_and(|v| v == "1") {
                    return module;
                }
            $calls    module
            }

            RUST);
    }

    /**
     * Creates or refreshes a port crate. port.rs is only written when missing (or replaced by a
     * reference); glue.rs, lib.rs and TASK.md are regenerated every time.
     *
     * @param list<array<string, mixed>> $cases
     * @return array<string, mixed> what state.json keeps about the port
     */
    public function port(Codebase $cb, Func $f, array $cases, ?string $reference = null): array
    {
        $id = $f->id();
        $dir = $this->project->path('ports', $id);
        @mkdir("$dir/src", 0777, true);
        $crate = self::crate($id);
        $fn = self::snake($f->name);

        // Types come from real calls only: derived edge cases (a list with a gap, invalid UTF-8)
        // are there to exercise the fallback, not to widen the types.
        $real = array_values(array_filter($cases, static fn ($c) => !$c['derived'])) ?: $cases;
        $ok = array_values(array_filter($real, static fn ($c) => !isset($c['exc']) && empty($c['warn'])));
        $rets = array_column($ok, 'ret');
        $retShape = $f->returnType !== null && !Types::declaredNullable($f->returnType)
            ? Types::param($f->returnType, $rets, true, $f->doc['return'])
            : Types::merge($f->doc['return'], Types::infer($rets));
        if ($retShape === 'never') {
            $retShape = 'mixed';
        }
        $fallback = !Types::nullable($retShape) && !($f->returnType !== null && Types::declaredNullable($f->returnType));
        $params = [];
        foreach ($f->params as $i => $p) {
            $shape = Types::param($p['type'], array_map(static fn ($c) => $c['args'][$i] ?? null, $real), $fallback, $f->doc['params'][$p['name']] ?? null);
            $params[] = $p + ['rust' => self::snake($p['name']), 'shape' => $shape, 'rustType' => Types::rust($shape), 'expr' => '$' . $p['name']];
        }
        // An instance method gets the properties it reads as extra arguments, after its own.
        $props = $f->static ? [] : $cb->props($f);
        foreach ($props as $j => $prop) {
            $i = count($f->params) + $j;
            $type = $cb->propType($f->class, $prop);
            $shape = Types::param($type, array_map(static fn ($c) => $c['args'][$i] ?? null, $real), $fallback);
            $params[] = [
                'name' => "this->$prop", 'type' => $type, 'default' => null, 'byRef' => false, 'variadic' => false,
                'rust' => 'this_' . self::snake($prop), 'shape' => $shape, 'rustType' => Types::rust($shape), 'expr' => "\$this->$prop",
            ];
        }
        $ret = Types::rust($retShape);

        file_put_contents("$dir/Cargo.toml", <<<TOML
            # Generated by fast-php.
            [package]
            name = "$crate"
            version = "0.0.0"
            edition.workspace = true
            publish.workspace = true

            [lib]
            crate-type = ["rlib", "cdylib"]

            [features]
            # Builds this port alone as an extension, for `fast-php verify`.
            standalone = []

            [dependencies]
            ext-php-rs.workspace = true
            fastphp-value.workspace = true
            fastphp-std.workspace = true

            TOML);
        file_put_contents("$dir/src/lib.rs", <<<RUST
            //! Generated by fast-php. The port itself is in port.rs.
            #![cfg_attr(windows, feature(abi_vectorcall))]

            pub mod port;
            mod glue;

            pub use glue::register;

            #[cfg(feature = "standalone")]
            #[ext_php_rs::prelude::php_module]
            pub fn get_module(module: ext_php_rs::prelude::ModuleBuilder) -> ext_php_rs::prelude::ModuleBuilder {
                register(module)
            }

            RUST);
        file_put_contents("$dir/src/glue.rs", $this->glue($id, $fn, $params, $ret, $fallback));
        $portFile = "$dir/src/port.rs";
        if ($reference !== null) {
            copy($reference, $portFile);
        } elseif (!is_file($portFile)) {
            file_put_contents($portFile, $this->stub($f, $fn, $params, $ret, $fallback));
        }
        file_put_contents("$dir/TASK.md", Task::render($this->project, $cb, $f, $params, $retShape, $ret, $fallback, $cases, $fn));

        return [
            'id' => $id,
            'name' => $f->display(),
            'class' => $f->class,
            'function' => $f->name,
            'file' => $this->project->rel($f->file),
            'line' => $f->line,
            'crate' => $crate,
            'native' => self::native($id),
            'fallback' => $fallback,
            'instance' => !$f->static,
            'props' => $props,
            'nargs' => count($f->params),
            'params' => array_map(static fn ($p) => ['name' => $p['name'], 'php' => $p['type'], 'rust' => $p['rustType'], 'expr' => $p['expr']], $params),
            'returns' => $ret,
        ];
    }

    /** @param list<array<string, mixed>> $params */
    private function glue(string $id, string $fn, array $params, string $ret, bool $fallback): string
    {
        $native = addslashes(self::native($id));
        $glueFn = 'fastphp_' . self::snake($id);
        $sig = implode(', ', array_map(static fn ($p) => "{$p['rust']}: &Zval", $params));
        $reads = '';
        foreach ($params as $i => $p) {
            $n = $i + 1;
            if ($fallback) {
                $reads .= "    let Some({$p['rust']}) = <{$p['rustType']}>::from_php({$p['rust']}) else { return Ok(Ret(None)) };\n";
            } else {
                $want = addslashes($p['type'] ?? 'mixed');
                $reads .= "    let {$p['rust']}: {$p['rustType']} = arg({$p['rust']}, $n, \"{$p['name']}\", \"$want\")?;\n";
            }
        }
        $args = implode(', ', array_column($params, 'rust'));
        $display = addslashes($id);
        // A panic must not unwind into the engine: it becomes a PHP Error.
        $call = "std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| crate::port::$fn($args)))\n"
            . "        .unwrap_or_else(|p| Err(PhpError::panicked(\"$display\", p)))";
        if ($fallback) {
            $body = <<<RUST
                    match $call {
                        Ok(v) => Ok(Ret(Some(v))),
                        Err(e) if e.is_fallback() => Ok(Ret(None)),
                        Err(e) => Err(e.into()),
                    }
                RUST;
            $type = "Ret<Option<$ret>>";
            $doc = "/// Returns null when an argument is outside the port's types (or the port declines): the\n/// prologue then lets the original PHP run.";
        } else {
            $body = "    $call\n        .map(Ret)\n        .map_err(Into::into)";
            $type = "Ret<$ret>";
            $doc = "/// The original can return null, so there is no fallback: arguments outside the types throw a TypeError.";
        }
        return <<<RUST
            //! Generated by fast-php from the PHP signature and the recorded calls. Don't edit: it is
            //! rewritten by `fast-php port`. Values are read and written without coercion.
            #![allow(unused_imports, clippy::all)]

            use ext_php_rs::exception::PhpException;
            use ext_php_rs::prelude::*;
            use ext_php_rs::types::Zval;
            use fastphp_value::*;

            $doc
            #[php_function]
            #[php(name = "$native")]
            pub fn $glueFn($sig) -> Result<$type, PhpException> {
            $reads$body
            }

            pub fn register(module: ModuleBuilder) -> ModuleBuilder {
                // fastphp-std follows the behaviour of the PHP this extension is built for.
                fastphp_std::set_php_version(fastphp_std::version_from_api(ext_php_rs::ffi::ZEND_MODULE_API_NO));
                module.function(wrap_function!($glueFn))
            }

            RUST;
    }

    /** @param list<array<string, mixed>> $params */
    private function stub(Func $f, string $fn, array $params, string $ret, bool $fallback): string
    {
        $sig = implode(', ', array_map(static fn ($p) => "{$p['rust']}: {$p['rustType']}", $params));
        $names = implode(', ', array_column($params, 'rust'));
        $where = $this->project->rel($f->file) . ':' . $f->line;
        $todo = $fallback
            ? "    // Not ported yet: declining every call makes PHP handle it.\n    Err(PhpError::fallback())"
            : "    todo!(\"port {$f->display()}\")";
        return <<<RUST
            //! Port of {$f->display()} ($where). Read ../TASK.md first.
            //! `fast-php verify {$f->id()}` replays the recorded calls against it.

            #[allow(unused_imports)]
            use fastphp_std::{array, cmp, conv, hash, math, mb, pcre, string};
            use fastphp_value::*;

            pub fn $fn($sig) -> Result<$ret, PhpError> {
                let _ = ($names);
            $todo
            }

            RUST;
    }
}
